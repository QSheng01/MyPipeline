using System;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.Rendering;

namespace MPipeline
{
    /// <summary>GPU quadtree terrain using the scene's TerrainData and AVT material.</summary>
    [ExecuteAlways, DisallowMultipleComponent, RequireComponent(typeof(Terrain))]
    public sealed class GPUTerrain : MonoBehaviour
    {
        public enum HeightSource { RuntimeTerrainData, BakedTextures }

        [Header("Height Data")]
        public HeightSource heightSource = HeightSource.RuntimeTerrainData;
        [Tooltip("RFloat height generated by Tools > GPU Terrain > Bake Height And Normals.")]
        public Texture2D bakedHeight;
        [Tooltip("Linear RGHalf world normal XZ generated alongside the height; Y is reconstructed in the shader.")]
        public Texture2D bakedNormal;
        [SerializeField, HideInInspector] private bool bakedHeightStale;
        public bool gpuRendering = true;
        [Tooltip("log2 of the finest patch count along one axis. Each leaf node contains 8x8 patches; the default 7 gives a 128x128 patch grid.")]
        [Range(1, 8)] public int finestGridExponent = 7;
        [Range(1f, 8f)] public float lodDistance = 3f;
        public bool frustumCulling = true;
        [Header("Scene View Culling")]
        [Tooltip("Use the game camera's LOD and frustum in Scene view, so moving the editor camera reveals which terrain patches the game camera rejects.")]
        public bool sceneViewUsesGameCamera = true;
        [Tooltip("Optional Scene-view culling source. When empty, use Main Camera. Game cameras always use their own frustum.")]
        public Camera sceneViewCullingCamera;
        public bool showCullingFrustum = true;
        [Header("Rendering")]
        public bool stitchEdges = true;
        [Tooltip("Use depth from the culling camera in Game and Scene views, including Edit mode. Moving the source camera invalidates history until its depth is refreshed.")]
        public bool hiZOcclusion = true;
        [Min(0.000001f)] public float hiZDepthBias = 0.0001f;
        [Min(0.1f)] public float boundsPadding = 2f;
        public bool castShadows = true;
        public bool debugLOD;
        public bool showHUD = true;
        [Tooltip("Optional asynchronous counters for the HUD. Rendering never waits for these results.")]
        public bool collectStatistics = true;
        [SerializeField] private ComputeShader buildShader;
        [SerializeField] private Shader terrainShader;
        [SerializeField, HideInInspector] private bool originalDrawHeightmap = true;
        [SerializeField, HideInInspector] private bool ownsDrawHeightmap;

        public bool IsReady => builder != null && builder.IsReady && material != null;
        public int GridSize => builder?.GridSize ?? 0;
        public int PatchGridSize => builder?.PatchGridSize ?? 0;
        public int PatchCapacity => builder?.PatchCapacity ?? 0;
        public int VisiblePatches { get; internal set; }
        public int SelectedPatches { get; internal set; }
        public int FrustumPatches { get; internal set; }
        public int HiZCulledPatches { get; internal set; }
        public bool LastUsedHiZ { get; internal set; }
        public string HiZStatus { get; internal set; } = "等待摄像机";
        public string Status { get; private set; } = "Waiting for camera";
        public Texture HeightTexture => builder?.HeightTexture;
        public bool UsingBakedTextures => builder != null && builder.asset.UseBaked;
        public bool BakedHeightStale => bakedHeightStale;
        public bool BakedTexturesValid => source != null && source.terrainData != null
            && bakedHeight != null && bakedNormal != null
            && bakedHeight.width == source.terrainData.heightmapResolution && bakedHeight.height == bakedHeight.width
            && bakedNormal.width == bakedHeight.width && bakedNormal.height == bakedHeight.height
            && bakedHeight.format == TextureFormat.RFloat && bakedNormal.format == TextureFormat.RGHalf;

        public struct CullingDiagnostics
        {
            public string SourceCamera, HiZStatus;
            public bool HiZActive, HasStatistics;
            public int Selected, Frustum, Occluded, Visible;
        }

        public bool TryGetDiagnostics(Camera renderingCamera, out CullingDiagnostics diagnostics)
        {
            if (builder != null) return builder.TryGetDiagnostics(renderingCamera, out diagnostics);
            diagnostics = default;
            return false;
        }

        // Editor preview uses this to refresh the actual source camera even when
        // only the Scene tab is visible. It never uses the observer's depth.
        public bool NeedsHiZDepthRefresh(Camera camera, double maximumAge = 0.1)
        {
            if (camera == null || !hiZOcclusion || !gpuRendering) return false;
            return !ClusterHiZResources.TryGetLatest(camera, out var data)
                || !data.Texture.IsCreated()
                || Time.realtimeSinceStartupAsDouble - data.PublishedTime > maximumAge
                || data.CameraMatrix != camera.projectionMatrix * camera.worldToCameraMatrix
                || data.Target != camera.targetTexture
                || data.CameraPixelSize != new Vector2Int(camera.pixelWidth, camera.pixelHeight);
        }

        public Camera GetCullingCamera(Camera renderingCamera)
        {
            if (renderingCamera != null && renderingCamera.cameraType == CameraType.SceneView && sceneViewUsesGameCamera)
            {
                Camera gameCamera = sceneViewCullingCamera != null ? sceneViewCullingCamera : Camera.main;
                if (gameCamera != null) return gameCamera;
            }
            return renderingCamera;
        }

        private Terrain source;
        private Material material;
        private TerrainBuilder builder;
        private bool reportedFailure;

        

        private void OnEnable()
        {
            source = GetComponent<Terrain>();
            RenderPipelineManager.beginCameraRendering += BeginCamera;
            TerrainCallbacks.heightmapChanged += HeightChanged;
            builder?.InvalidateHeight();
        }

        private void OnDisable()
        {
            RenderPipelineManager.beginCameraRendering -= BeginCamera;
            TerrainCallbacks.heightmapChanged -= HeightChanged;
            RestoreTerrain();
            ReleaseResources();
        }

        private void HeightChanged(Terrain terrain, RectInt region, bool synced)
        {
            if (terrain != source) return;
            bakedHeightStale = true;
            builder?.InvalidateHeight();
        }

        public void MarkBakedHeightCurrent()
        {
            bakedHeightStale = false;
            // Re-baking can update the same Texture2D object in place. The
            // references still match, but its MinMax hierarchy is now stale.
            builder?.InvalidateHeight();
        }

        private void OnValidate()
        {
            finestGridExponent = Mathf.Clamp(finestGridExponent, 1, 8);
            lodDistance = Mathf.Clamp(lodDistance, 1, 8);
            boundsPadding = Mathf.Max(0.1f, boundsPadding);
            hiZDepthBias = Mathf.Max(0.000001f, hiZDepthBias);
            builder?.InvalidateHeight();
        }

        private void Update()
        {
            if (!gpuRendering || source == null || !source.enabled) RestoreTerrain();
        }

        private void RestoreTerrain()
        {
            if (source != null && ownsDrawHeightmap) source.drawHeightmap = originalDrawHeightmap;
            ownsDrawHeightmap = false;
        }

        private bool EnsureResources()
        {
            if (source == null || source.terrainData == null || source.materialTemplate == null)
            { Status = "TerrainData / AVT material missing"; return false; }
            if (!SystemInfo.supportsComputeShaders || !SystemInfo.supportsInstancing || SystemInfo.graphicsShaderLevel < 50)
            { Status = "GPU unsupported: Unity Terrain fallback"; return false; }
            if (source.materialTemplate.shader.name != "URP/TerrainMaterialIDVT")
            { Status = "Requires the existing URP/TerrainMaterialIDVT material"; return false; }
            if (transform.rotation != Quaternion.identity || transform.lossyScale != Vector3.one)
            { Status = "Use an unrotated Terrain with unit scale"; return false; }
            if (buildShader == null) buildShader = Resources.Load<ComputeShader>("GPUTerrainBuild");
            if (terrainShader == null) terrainShader = Shader.Find("MPipeline/GPU Terrain AVT");
            if (buildShader == null || terrainShader == null || !terrainShader.isSupported)
            { Status = "GPU terrain shaders unavailable"; return false; }

            int resolution = source.terrainData.heightmapResolution;
            int maxLOD = Mathf.Clamp(finestGridExponent - 3, 0,
                Mathf.Max(0, (int)Mathf.Log((resolution - 1) / (TerrainAsset.PatchesPerNode * TerrainAsset.PatchMeshGridCount), 2)));
            bool baked = heightSource == HeightSource.BakedTextures && !bakedHeightStale;
            if (baked && !BakedTexturesValid)
            { Status = "Baked height/normal missing or wrong resolution/format; Unity Terrain fallback"; return false; }
            if (builder == null || builder.asset.Data != source.terrainData || builder.asset.MaxLOD != maxLOD
                || builder.asset.UseBaked != baked
                || (baked && (builder.asset.BakedHeight != bakedHeight || builder.asset.BakedNormal != bakedNormal))
                || !builder.IsReady)
            {
                ReleaseResources();
                var asset = new TerrainAsset(source, buildShader, terrainShader, maxLOD,
                    baked ? bakedHeight : null, baked ? bakedNormal : null);
                builder = new TerrainBuilder(this, asset);
                material = new Material(terrainShader) { name = "GPU Terrain AVT (Runtime)", hideFlags = HideFlags.HideAndDontSave, enableInstancing = true };
            }
            material.CopyPropertiesFromMaterial(source.materialTemplate);
            material.enableInstancing = true;
            material.DisableKeyword("_TERRAIN_INSTANCED_PERPIXEL_NORMAL");
            return true;
        }

        private void ReleaseResources()
        {
            builder?.Dispose(); builder = null;
            CoreUtils.Destroy(material); material = null;
        }

        private void BeginCamera(ScriptableRenderContext context, Camera camera)
        {
            if (camera == null || camera.cameraType == CameraType.Preview) return;
            if (!gpuRendering || source == null || !source.enabled)
            { RestoreTerrain(); Status = "Unity Terrain"; return; }
            if ((camera.cullingMask & (1 << gameObject.layer)) == 0) return;
            try
            {
                if (!EnsureResources()) { RestoreTerrain(); return; }
                var buffers = builder.Dispatch(camera, GetCullingCamera(camera));
                if (!ownsDrawHeightmap) { originalDrawHeightmap = source.drawHeightmap; ownsDrawHeightmap = true; }
                source.drawHeightmap = false;
                builder.BindProperties(buffers.Properties, buffers.Visible);
                builder.BindProperties(buffers.ShadowProperties, buffers.Shadow);
                Bounds bounds = new Bounds(transform.position + source.terrainData.size * 0.5f, source.terrainData.size + Vector3.one * boundsPadding * 2);
                // This callback is before URP's Cull. Unity routes indirect draws through
                // its ordinary forward/GBuffer, depth and shadow passes, including AVT UAVs.
                Graphics.DrawMeshInstancedIndirect(builder.PatchMesh, 0, material, bounds, buffers.Args, 0, buffers.Properties,
                    ShadowCastingMode.Off, true, gameObject.layer, camera, LightProbeUsage.Off);
                if (castShadows)
                    Graphics.DrawMeshInstancedIndirect(builder.PatchMesh, 0, material, bounds, buffers.ShadowArgs, 0, buffers.ShadowProperties,
                        ShadowCastingMode.ShadowsOnly, false, gameObject.layer, camera, LightProbeUsage.Off);
                if (camera == Camera.main)
                {
                    Status = UsingBakedTextures ? "GPU quadtree / baked height + normal"
                        : bakedHeightStale && heightSource == HeightSource.BakedTextures
                            ? "GPU quadtree / TerrainData (bake stale; rebake needed)"
                            : "GPU quadtree / runtime height + normal";
                }
                builder.RequestStatistics(camera, buffers);
                reportedFailure = false;
            }
            catch (Exception error)
            {
                RestoreTerrain();
                ReleaseResources();
                Status = "Unity Terrain fallback: " + error.Message;
                if (!reportedFailure) Debug.LogException(error, this);
                reportedFailure = true;
            }
        }

        

        

        

        

        

        private void OnGUI()
        {
            if (!showHUD || !Application.isPlaying) return;
            GUILayout.BeginArea(new Rect(Mathf.Max(364, Screen.width - 318), Mathf.Max(12, Screen.height - 286), 306, 274), GUI.skin.box);
            GUILayout.Label("GPU Driven Terrain");
            if (GUILayout.Button(gpuRendering ? "Geometry: GPU" : "Geometry: Unity Terrain")) gpuRendering = !gpuRendering;
            debugLOD = GUILayout.Toggle(debugLOD, "LOD colors + patch edges");
            frustumCulling = GUILayout.Toggle(frustumCulling, "GPU frustum culling");
            hiZOcclusion = GUILayout.Toggle(hiZOcclusion, "Hi-Z culling");
            GUILayout.Label(UsingBakedTextures ? "Height + normal: baked assets" : "Height + normal: runtime TerrainData");
            GUILayout.Label("LOD distance: " + lodDistance.ToString("0.0"));
            lodDistance = GUILayout.HorizontalSlider(lodDistance, 1, 8);
            GUILayout.Label($"Visible {VisiblePatches} / selected {SelectedPatches} / max {PatchCapacity}");
            GUILayout.Label($"Frustum {FrustumPatches} / Hi-Z rejected {HiZCulledPatches}");
            GUILayout.Label("Hi-Z: " + HiZStatus);
            GUILayout.Label(Status);
            GUILayout.EndArea();
        }

#if UNITY_EDITOR
        private readonly Vector3[] nearFrustum = new Vector3[4];
        private readonly Vector3[] farFrustum = new Vector3[4];

        private void OnDrawGizmos()
        {
            if (!enabled || !gpuRendering || !sceneViewUsesGameCamera || !showCullingFrustum) return;
            Camera camera = sceneViewCullingCamera != null ? sceneViewCullingCamera : Camera.main;
            if (camera == null) return;
            camera.CalculateFrustumCorners(new Rect(0, 0, 1, 1), camera.nearClipPlane, Camera.MonoOrStereoscopicEye.Mono, nearFrustum);
            camera.CalculateFrustumCorners(new Rect(0, 0, 1, 1), camera.farClipPlane, Camera.MonoOrStereoscopicEye.Mono, farFrustum);
            Color previousColor = Gizmos.color;
            Matrix4x4 previousMatrix = Gizmos.matrix;
            Gizmos.color = new Color(0.1f, 0.9f, 1f, 1f);
            Gizmos.matrix = camera.transform.localToWorldMatrix;
            for (int i = 0; i < 4; i++)
            {
                int next = (i + 1) % 4;
                Gizmos.DrawLine(nearFrustum[i], nearFrustum[next]);
                Gizmos.DrawLine(farFrustum[i], farFrustum[next]);
                Gizmos.DrawLine(nearFrustum[i], farFrustum[i]);
            }
            Gizmos.color = previousColor;
            Gizmos.matrix = previousMatrix;
        }
#endif
    }
}
